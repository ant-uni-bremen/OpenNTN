_MODELS = {"urb": Urban, "dur": DenseUrban, "sur": SubUrban}
_CARRIER = {("s_band", "downlink"): 2.2e9, ("s_band", "uplink"): 2.0e9,
            ("ka_band", "downlink"): 20.0e9, ("ka_band", "uplink"): 30.0e9}
