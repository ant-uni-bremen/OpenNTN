_ELEVS = (10, 20, 30, 40, 50, 60, 70, 80, 90)
_DIRS = (("dl", "downlink"), ("ul", "uplink"))


def _build_model(scenario, band, elevation, direction):
    carrier_frequency = _CARRIER[(band, direction)]
    ut_array = create_ut_ant(carrier_frequency)
    bs_array = create_bs_ant(carrier_frequency)
    channel_model = _MODELS[scenario](carrier_frequency=carrier_frequency,
                                      ut_array=ut_array,
                                      bs_array=bs_array,
                                      direction=direction,
                                      elevation_angle=float(elevation),
                                      enable_pathloss=True,
                                      enable_shadow_fading=True)
    batch_size, num_ut = _TOPO.get((scenario, band, elevation, direction), (100, 100))
    topology = utils.gen_single_sector_topology(batch_size=batch_size, num_ut=num_ut,
                                                scenario=scenario,
                                                elevation_angle=float(elevation),
                                                bs_height=600000.0)
    channel_model.set_topology(*topology)
    return channel_model

